import { mkdir, copyFile, readFile, rm } from "node:fs/promises";

// Android/PWA runtime must not package isolated proof-of-concept archive-v2
// modules that are not loaded by the application. The originals stay in js/
// for tests and code review; this only cleans generated www/js output.
const html = await readFile("index.html", "utf8");
const worker = await readFile("sw.js", "utf8");
const loaded = [...html.matchAll(/<script\b[^>]*\bsrc\s*=\s*(["'])\.\/js\/([A-Za-z0-9_.-]+\.js)\1/gi)]
  .map(match => match[2]);
const cached = [...worker.matchAll(/(["'])\.\/js\/([A-Za-z0-9_.-]+\.js)\1/g)]
  .map(match => match[2]);
const unique = values => new Set(values);
const loadedSet = unique(loaded), cachedSet = unique(cached);
if (!loaded.length || loaded.length !== loadedSet.size || cached.length !== cachedSet.size ||
    [...loadedSet].some(file => file.includes("..") || !cachedSet.has(file)) ||
    [...cachedSet].some(file => !loadedSet.has(file))) {
  throw new Error("Runtime scripts and offline Service Worker cache are inconsistent. Android build stopped.");
}

await mkdir("www", { recursive: true });
await mkdir("www/icons", { recursive: true });
for (const file of ["index.html", "manifest.webmanifest", "sw.js"]) {
  await copyFile(file, `www/${file}`);
}
await copyFile("icons/paseka.svg", "www/icons/paseka.svg");
// www/js is generated by this script, never a user-data store. Remove stale
// generated files before the copy so older isolated prototypes stay excluded.
await rm("www/js", { recursive: true, force: true });
await mkdir("www/js", { recursive: true });
for (const file of loadedSet) {
  await copyFile(`js/${file}`, `www/js/${file}`);
}
console.log(`P2_ANDROID_RUNTIME_SCRIPTS=${loadedSet.size}`);
