test('native patch is idempotent and preserves distinct package/origin',()=>{
 const config={appId:'ru.paseka.journal',webDir:'www',android:{allowMixedContent:false}};
 const qa=dailyQaConfig(config);
 assert.equal(qa.appId,'ru.paseka.journal.qa.daily');assert.equal(config.appId,'ru.paseka.journal');
 assert.equal(assertDailyConfig(qa),qa.appId);
 const diag=dailyQaConfig(config,{diagnostic:true});
 assert.equal(diag.appId,'ru.paseka.journal.qa.daily.diag');
 assert.equal(assertDailyConfig(diag),diag.appId);
 assert.notEqual(diag.appId,qa.appId);
 const probe=dailyQaConfig(config,{probe:true});
 const dom=dailyQaConfig(config,{dom:true});
 const fixed=dailyQaConfig(config,{fix:true});
 assert.equal(fixed.appId,'ru.paseka.journal.qa.daily.fix');
 assert.equal(assertDailyConfig(fixed),fixed.appId);
 for(const other of [qa,diag,probe,dom])assert.notEqual(fixed.appId,other.appId);
 assert.throws(()=>dailyQaConfig(config,{dom:true,fix:true}),/unexpected/);
 assert.throws(()=>assertDailyConfig({...fixed,server:{url:'https://remote.test'}}),/origin/);
 assert.equal(dom.appId,'ru.paseka.journal.qa.daily.dom');
 assert.equal(assertDailyConfig(dom),dom.appId);
 assert.notEqual(dom.appId,qa.appId);
 assert.notEqual(dom.appId,probe.appId);
 assert.notEqual(dom.appId,diag.appId);
 assert.throws(()=>dailyQaConfig(config,{probe:true,dom:true}),/unexpected/);
 assert.throws(()=>assertDailyConfig({...dom,server:{url:'https://remote.test'}}),/origin/);
 assert.equal(probe.appId,'ru.paseka.journal.qa.daily.probe');
 assert.equal(assertDailyConfig(probe),probe.appId);
 assert.notEqual(probe.appId,qa.appId);
 assert.notEqual(probe.appId,diag.appId);
 assert.throws(()=>dailyQaConfig(config,{probe:true,diagnostic:true}),/unexpected/);
 assert.throws(()=>assertDailyConfig({...probe,server:{url:'https://remote.test'}}),/origin/);
 assert.throws(()=>assertDailyConfig({...diag,server:{url:'https://remote.test'}}),/origin/);
 assert.throws(()=>assertDailyConfig({...config,server:{androidScheme:'http'}}),/origin/);
 assert.throws(()=>assertDailyConfig({...config,server:{url:'https://example.test'}}),/origin/);
 const main='package '+qa.appId+';\npublic class MainActivity extends BridgeActivity {}';
 const patched=patchActivity(main,qa.appId);
 assert.equal(patchActivity(patched,qa.appId),patched);
 assert.match(patched,/PasekaDailyArchiveJob\.schedule\(this\)/);
 const manifest='<manifest><application></application></manifest>',xml=patchManifest(manifest);
 assert.equal(patchManifest(xml),xml);
 assert.match(xml,/android\.permission\.BIND_JOB_SERVICE/);
 assert.match(xml,/android\.permission\.RECEIVE_BOOT_COMPLETED/);
 const diagnosticActivity='package '+diag.appId+';\npublic class MainActivity extends BridgeActivity {}';
 assert.match(patchActivity(diagnosticActivity,diag.appId),/PasekaDailyArchiveJob\.schedule\(this\)/);
});
