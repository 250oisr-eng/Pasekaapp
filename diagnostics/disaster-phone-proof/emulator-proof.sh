#!/usr/bin/env bash
set -euo pipefail
# ONLY the isolated test package; never the production application.
package='ru.paseka.journal.disasterproof'
apk="$(find diagnostic-artifact -type f -name app-debug.apk -print -quit)"
test -n "$apk" && test -f "$apk" || { echo 'P0_APK_MISSING'; exit 1; }
adb install -r "$apk"
adb shell pm path "$package" | grep -F 'package:'
# Only the disposable ru.paseka.journal.disasterproof package is reset.
# A reused emulator may retain an empty, previously-created database; the
# production app correctly refuses to self-initialize such an ambiguous DB.
# Resetting this isolated package BEFORE the first launch is safe. Never clear
# the application in the middle of the restore/restart proof.
test "$package" = 'ru.paseka.journal.disasterproof'
adb shell pm clear "$package" | grep -Fx 'Success'
echo P0_ISOLATED_DIAGNOSTIC_PACKAGE_CLEARED_BEFORE_FIRST_LAUNCH
capture() {
 local stage="$1"
 adb exec-out screencap -p > "disaster-emulator-${stage}.png" || true
 adb logcat -d -v brief > "disaster-emulator-${stage}.log" || true
 adb shell uiautomator dump /sdcard/paseka-p0-accessibility.xml > "disaster-emulator-${stage}-uiautomator.txt" 2>&1 || true
 adb exec-out cat /sdcard/paseka-p0-accessibility.xml > "disaster-emulator-${stage}.xml" 2>/dev/null || true
 grep -F 'PASEKA_P0_DISASTER_PROOF_RESULT' "disaster-emulator-${stage}.log" | tail -n 8 > "disaster-emulator-${stage}-result.txt" || true
}
ui_confirmed() {
 local stage="$1" code="$2"
 python3 - "disaster-emulator-${stage}.xml" "$code" <<'PY'
import sys, xml.etree.ElementTree as ET, html, re
path, expected = sys.argv[1:]
try:
    tree = ET.parse(path)
    texts=[]
    for node in tree.iter():
        texts.extend(html.unescape(node.attrib.get(k,'')) for k in ('text','content-desc'))
    observed=' '.join(texts)
    # The overlay is generated by the diagnostic package only, and all
    # essential fields must be visible in the fresh accessibility dump.
    good = (
        re.search(r'"status"\s*:\s*"PASS"',observed) is not None
        and re.search(r'"code"\s*:\s*"'+re.escape(expected)+r'"',observed) is not None
        and re.search(r'"packageId"\s*:\s*"ru\.paseka\.journal\.disasterproof"',observed) is not None
        and re.search(r'"productionDatabase"\s*:\s*"NOT_ACCESSED"',observed) is not None
    )
except Exception as error:
    print('P0_UI_PROOF_UNAVAILABLE:', type(error).__name__, str(error))
    sys.exit(1)
if not good:
    print('P0_UI_ACCESSIBILITY_NOT_CONFIRMED expected:',expected,'chars:',len(observed))
    sys.exit(1)
print('P0_UI_ACCESSIBILITY_CONFIRMED',expected)
PY
}
confirmed() {
 local stage="$1" code="$2"
 if grep -F "$code" "disaster-emulator-${stage}-result.txt" | grep -F '"status":"PASS"' >/dev/null; then
  echo "P0_LOGCAT_PROOF_CONFIRMED $code"
  return 0
 fi
 ui_confirmed "$stage" "$code"
}
adb logcat -c || true
adb shell monkey -p "$package" -c android.intent.category.LAUNCHER 1
sleep 25
capture first
confirmed first P0_DISASTER_WEBVIEW_RESTORE_PASS || {
 echo 'P0_EMULATOR_RESTORE_BLOCKED'; cat disaster-emulator-first-result.txt || true
 tail -n 60 disaster-emulator-first.log | grep -Ei 'paseka|webview|chromium|console|error|exception' || true
 exit 1
}
adb shell am force-stop "$package"
adb logcat -c || true
adb shell monkey -p "$package" -c android.intent.category.LAUNCHER 1
sleep 15
capture restart
confirmed restart P0_DISASTER_PHYSICAL_RESTART_PASS || {
 echo 'P0_EMULATOR_RESTART_BLOCKED'; cat disaster-emulator-restart-result.txt || true
 tail -n 60 disaster-emulator-restart.log | grep -Ei 'paseka|webview|chromium|console|error|exception' || true
 exit 1
}
echo PASS_P0_ANDROID_EMULATOR_DISASTER_RESTORE_AND_RESTART
